// Offline: the sprite produced by icons.mjs is the only source of drawings.
// node design/tools/generate-icons.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const header = '// <auto-generated by design/tools/generate-icons.mjs; see THIRD-PARTY-NOTICES.md />\n';

export function generateIcons(sprite) {
  const properties = [];
  const entries = [];
  const names = new Set();
  for (const line of sprite.trim().split(/\r?\n/).map(line => line.trim())) {
    if (!line || line === '<svg xmlns="http://www.w3.org/2000/svg">' || line === '</svg>' || /^<!--.*-->$/.test(line)) continue;
    const symbol = /^<symbol id="([a-z0-9]+(?:-[a-z0-9]+)*)" viewBox="0 0 24 24">(.+)<\/symbol>$/.exec(line);
    if (!symbol) throw new Error(`Unexpected sprite symbol: ${line}`);

    // PascalCase is distinct from lowercase C# keywords. Prefix a leading digit with Icon.
    const [, id, content] = symbol;
    const name = id.replace(/(^|-)([a-z0-9])/g, (_, dash, char) => char.toUpperCase()).replace(/^(?=\d)/, 'Icon');
    if (names.has(name)) throw new Error(`Duplicate icon member: ${name}`);
    names.add(name);
    properties.push(`    public static FlIconDefinition ${name} => new(@"${content.replaceAll('"', '""')}");`);
    entries.push(`        (nameof(FlIcons.${name}), FlIcons.${name}),`);
  }
  if (!names.size) throw new Error('Empty icon sprite');
  return {
    library: `${header}\nnamespace FluentCMS.Components;\n\npublic static class FlIcons\n{\n${properties.join('\n')}\n}\n`,
    gallery: `${header}\nusing FluentCMS.Components;\n\nnamespace Gallery.Client;\n\ninternal static class GalleryIcons\n{\n    internal static IReadOnlyList<(string Name, FlIconDefinition Icon)> All { get; } =\n    [\n${entries.join('\n')}\n    ];\n}\n`,
  };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv[2] === '--check';
  if (process.argv.length !== (check ? 3 : 2)) throw new Error('Usage: node design/tools/generate-icons.mjs [--check]');
  const root = new URL('../../', import.meta.url);
  const { library, gallery } = generateIcons(readFileSync(new URL('design/system/icons/lucide.svg', root), 'utf8'));
  for (const [path, content] of [
    ['src/FluentCMS.Components/Foundations/FlIcons.g.cs', library],
    ['gallery/Gallery.Client/GalleryIcons.g.cs', gallery],
  ]) {
    const file = fileURLToPath(new URL(path, root));
    if (check) {
      if (readFileSync(file, 'utf8') !== content) throw new Error(`${path} differs; rerun the icon generator`);
    } else {
      writeFileSync(file, content);
    }
  }
}
