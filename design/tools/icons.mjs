// Builds the icon sprites of the design system from pinned package versions.
//
//   node design/tools/icons.mjs
//
// design/system/icons/lucide.svg      the icon set (Lucide, ISC)
// design/system/docs/fluent-sample.svg  a sample of Fluent System Icons (MIT),
//                                       only for the comparison of O3 on the tokens page
//
// An icon is used as <svg class="fl-icon"><use href="icons/lucide.svg#name"/></svg>.
// The <svg> carries no viewBox: the symbol has its own.

