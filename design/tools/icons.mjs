async function inner(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status} ${url}`);
  const svg = await response.text();
  const m = svg.replace(/<!--[\s\S]*?-->/g, '').match(/<svg[^>]*>([\s\S]*)<\/svg>/);
  if (!m) throw new Error(`No <svg> in ${url}`);
  return m[1].replace(/\s*\n\s*/g, '').trim();
}

async function sprite(entries, note) {
  const results = await Promise.allSettled(entries.map(e => inner(e.url)));
  const missing = results.flatMap((r, i) => (r.status === 'rejected' ? [`${entries[i].id}: ${r.reason.message}`] : []));
  if (missing.length) throw new Error(`Missing icons:\n${missing.join('\n')}`);
  const symbols = results.map((r, i) => `<symbol id="${entries[i].id}" viewBox="${entries[i].viewBox}">${entries[i].map(r.value)}</symbol>`);
  return `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- ${note} Generated by design/tools/icons.mjs; do not edit by hand. -->\n${symbols.join('\n')}\n</svg>\n`;
}

const out = path => fileURLToPath(new URL(`../system/${path}`, import.meta.url));

writeFileSync(out('icons/lucide.svg'), await sprite(
  lucide.map(name => ({ id: name, viewBox: '0 0 24 24', url: `https://cdn.jsdelivr.net/npm/${LUCIDE}/icons/${name}.svg`, map: s => s })),
  `Lucide (${LUCIDE}), ISC license, see THIRD-PARTY-NOTICES.md.`,
));
console.log(`icons/lucide.svg: ${lucide.length} icons`);

// Fluent icons are filled shapes drawn once per size; the sample holds the 16
// and the 20 px drawings. The fill is set on the paths so that the stroke rules
// of .fl-icon do not apply to them.
writeFileSync(out('docs/fluent-sample.svg'), await sprite(
  [16, 20].flatMap(size => fluent.map(([name, id]) => ({
    id: `${id}-${size}`,
    viewBox: `0 0 ${size} ${size}`,
    url: `https://cdn.jsdelivr.net/npm/${FLUENT}/icons/${name}_${size}_regular.svg`,
    map: s => s.replace(/\s*fill="[^"]*"/g, '').replace(/<path /g, '<path fill="currentColor" stroke="none" '),
  }))),
  `Fluent System Icons (${FLUENT}), MIT license, see THIRD-PARTY-NOTICES.md.`,
));
console.log(`docs/fluent-sample.svg: ${fluent.length} icons in two sizes`);
